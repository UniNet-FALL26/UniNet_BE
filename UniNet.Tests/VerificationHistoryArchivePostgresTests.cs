    private static async Task<string> RowsAsync(UniNetDbContext db, string table, string? schema = null)
    {
        await db.Database.OpenConnectionAsync(); await using var command = db.Database.GetDbConnection().CreateCommand();
        command.CommandText = "SET timezone = 'UTC'; SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY \"Id\"),'[]'::jsonb)::text FROM " +
            (schema == null ? "" : '"' + schema + "\".") + '"' + table + "\" t";
        return (string)(await command.ExecuteScalarAsync())!;
    }

    private static async Task RunPostgresToolAsync(string name, NpgsqlConnectionStringBuilder connection, params string[] args)
    {
        var bin = Environment.GetEnvironmentVariable("UNINET_POSTGRES_BIN") ?? (OperatingSystem.IsWindows() ? @"C:\Program Files\PostgreSQL\18\bin" : "");
        var start = new ProcessStartInfo(Path.Combine(bin, name + (OperatingSystem.IsWindows() ? ".exe" : "")))
            { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, CreateNoWindow = true };
        foreach (var arg in args) start.ArgumentList.Add(arg);
        start.Environment["PGHOST"] = connection.Host;
        start.Environment["PGPORT"] = connection.Port.ToString();
        start.Environment["PGDATABASE"] = connection.Database;
        start.Environment["PGUSER"] = connection.Username;
        start.Environment["PGPASSWORD"] = connection.Password;
        start.Environment["PGSSLMODE"] = connection.SslMode.ToString().ToLowerInvariant().Replace("verifyfull", "verify-full").Replace("verifyca", "verify-ca");
        start.Environment["PGCONNECT_TIMEOUT"] = "15";
        using var process = Process.Start(start)!;
        var output = process.StandardOutput.ReadToEndAsync(); var error = process.StandardError.ReadToEndAsync();
        using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        await process.WaitForExitAsync(deadline.Token); await output;
        Assert.True(process.ExitCode == 0, await error);
    }

    [EvidencePostgresFact]
    public async Task NonemptyArchiveSurvivesPgDumpRestoreAndCanStillRollback()
    {
        await using var store = new Store(); await store.InitializeAsync();
        await using var db = store.Open(); await SeedAsync(db);
        var actions = await RowsAsync(db, "VerificationAdminAction"); var versions = await RowsAsync(db, "VerificationReportVersions");
        await db.Database.MigrateAsync();
        var connection = new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("UNINET_TEST_POSTGRES")!);
        var clone = "g2_restore_" + Guid.NewGuid().ToString("N");
        var dump = Path.Combine(Path.GetTempPath(), clone + ".dump");
        await using var admin = new NpgsqlConnection(connection.ConnectionString); await admin.OpenAsync();
        await new NpgsqlCommand($"CREATE DATABASE {clone}", admin).ExecuteNonQueryAsync();
        try
        {
            await RunPostgresToolAsync("pg_dump", connection, "-w", "--format=custom", "--schema=" + store.Schema, "--schema=" + store.Archive, "--file=" + dump);
            var cloneConnection = new NpgsqlConnectionStringBuilder(connection.ConnectionString) { Database = clone, SearchPath = store.Schema };
            await RunPostgresToolAsync("pg_restore", cloneConnection, "-w", "--exit-on-error", "--no-owner", "--no-privileges", "--dbname=" + clone, dump);
            await using var restored = new UniNetDbContext(new DbContextOptionsBuilder<UniNetDbContext>().UseNpgsql(cloneConnection.ConnectionString,
                options => options.MigrationsHistoryTable("__EFMigrationsHistory", store.Schema)).Options);
            Assert.Equal(actions, await RowsAsync(restored, "VerificationAdminAction", store.Archive));
            Assert.Equal(versions, await RowsAsync(restored, "VerificationReportVersions", store.Archive));
            await restored.GetService<IMigrator>().MigrateAsync(Before);
            Assert.Equal(actions, await RowsAsync(restored, "VerificationAdminAction"));
            Assert.Equal(versions, await RowsAsync(restored, "VerificationReportVersions"));
        }
        finally
        {
            await new NpgsqlCommand($"DROP DATABASE {clone} WITH (FORCE)", admin).ExecuteNonQueryAsync();
            if (File.Exists(dump)) File.Delete(dump);
        }
    }

    [EvidencePostgresFact]
    public async Task ArchivesEveryRevisionAndActionWithKeysConstraintsAndRefundAuditIntact()
    {
        await using var store = new Store(); await store.InitializeAsync();
        await using var db = store.Open(); var seed = await SeedAsync(db);
        await db.Database.ExecuteSqlRawAsync("CREATE TABLE external_history_reference (action_id uuid REFERENCES \"VerificationAdminAction\"(\"Id\"), version_id uuid REFERENCES \"VerificationReportVersions\"(\"Id\"));");
        var tables = new[] { "VerificationAdminAction", "VerificationReportVersions", "VerificationReports", "RefundTransactions", "ReportAuditLogs", "ProjectVerifications" };
        var before = new Dictionary<string, string>(); foreach (var table in tables) before[table] = await RowsAsync(db, table);
        await db.Database.MigrateAsync(); db.ChangeTracker.Clear();
        foreach (var table in tables)
            Assert.Equal(before[table], await RowsAsync(db, table, table is "VerificationAdminAction" or "VerificationReportVersions" ? store.Archive : null));
        Assert.DoesNotContain(db.Model.GetEntityTypes(), e => e.ClrType.Name is "VerificationAdminAction" or "VerificationReportVersion");
        var refunds = await db.RefundTransactions.ToListAsync();
        Assert.Equal(2, refunds.Count(r => r.RequestSource == RefundRequestSource.Admin));
        Assert.Single(refunds, r => r.RequestSource == RefundRequestSource.System && r.RequestedByUserId == null);
        Assert.Single(refunds, r => r.RequestSource == RefundRequestSource.LegacyUnknown && r.RequestedByUserId == null);
        await db.Database.ExecuteSqlRawAsync($"INSERT INTO external_history_reference SELECT (SELECT \"Id\" FROM {store.Archive}.\"VerificationAdminAction\" LIMIT 1), (SELECT \"Id\" FROM {store.Archive}.\"VerificationReportVersions\" LIMIT 1)");
        await db.GetService<IMigrator>().MigrateAsync(Before);
        foreach (var table in tables) Assert.Equal(before[table], await RowsAsync(db, table));
        // Downgrade through D/E must find the restored tables and preserve the new Admin refund actor.
        await db.Database.ExecuteSqlRawAsync("DROP TABLE external_history_reference");
        await db.GetService<IMigrator>().MigrateAsync(BeforeDE);
        await db.Database.OpenConnectionAsync(); await using var command = db.Database.GetDbConnection().CreateCommand();
        command.CommandText = "SELECT \"Summary\" FROM \"VerificationReports\"";
        Assert.Equal("original", await command.ExecuteScalarAsync());
        command.CommandText = $"SELECT \"ActorUserId\" FROM \"VerificationAdminAction\" WHERE \"RefundId\" = '{seed.NewAdminRefund}'";
        Assert.Equal(seed.Admin, await command.ExecuteScalarAsync());
        command.CommandText = "SELECT count(*) FROM \"VerificationReportVersions\"";
        Assert.Equal(2L, await command.ExecuteScalarAsync());
    }

