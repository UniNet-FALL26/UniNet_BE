using System.Net;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Microsoft.Extensions.Configuration;
using UniNet.Application;
using UniNet.Application.Services;
using UniNet.Domain.Enums;
using Xunit;

namespace UniNet.Tests;

public sealed class PayOSPaymentProviderTests
{
    private const string Key = "1a54716c8f0efb2744fb28b6e38b25da7f67a925d98bc1c18bd8faaecadd7675";
    private static IConfiguration Configuration() => new ConfigurationBuilder().AddInMemoryCollection(
        new Dictionary<string, string?> { ["PayOS:ClientId"] = "client", ["PayOS:ApiKey"] = "api", ["PayOS:ChecksumKey"] = Key }).Build();

    // Published PayOS payment-requests signature vector, not generated by production code.
    private const string OfficialSample = """
        {"code":"00","desc":"success","success":true,"data":{
          "orderCode":123,"amount":3000,"description":"VQRIO123","accountNumber":"12345678",
          "reference":"TF230204212323","transactionDateTime":"2023-02-04 18:25:00","currency":"VND",
          "paymentLinkId":"124c33293c43417ab7879e14c8d9eb18","code":"00","desc":"Thành công",
          "counterAccountBankId":"","counterAccountBankName":"","counterAccountName":"",
          "counterAccountNumber":"","virtualAccountName":"","virtualAccountNumber":""},
          "signature":"412e915d2871504ed31be63c8f62a149a4410d34c4c42affc9006ef9917eaa03"}
        """;

    [Fact]
    public void OfficialWebhookSignatureVectorIsAccepted()
    {
        using var http = new HttpClient();
        var provider = new PayOSPaymentProvider(http, Configuration());
        var result = provider.VerifyWebhook(JsonSerializer.Deserialize<JsonElement>(OfficialSample));
        Assert.Equal("123", result.OrderCode);
        Assert.Equal(3000, result.AmountVnd);
        Assert.Equal(PaymentStatus.Success, result.Status);
    }

    [Theory]
    [InlineData("3000", "3001")]
    [InlineData("412e915d", "ffffffff")]
    public void InvalidSignatureOrTamperedAmountIsRejected(string original, string replacement)
    {
        using var http = new HttpClient();
        var provider = new PayOSPaymentProvider(http, Configuration());
        var error = Assert.Throws<TransactionException>(() => provider.VerifyWebhook(
            JsonSerializer.Deserialize<JsonElement>(OfficialSample.Replace(original, replacement))));
        Assert.Equal("INVALID_WEBHOOK_SIGNATURE", error.Code);
    }

    [Fact]
    public void UnsignedOuterFieldsCannotOverrideSignedPaymentData()
    {
        using var http = new HttpClient();
        var provider = new PayOSPaymentProvider(http, Configuration());
        Assert.Equal(PaymentStatus.Success, provider.VerifyWebhook(JsonSerializer.Deserialize<JsonElement>(
            OfficialSample.Replace("\"success\":true", "\"success\":false"))).Status);
    }

    [Theory]
    [InlineData("{}")]
    [InlineData("{\"data\":null,\"signature\":\"invalid\"}")]
    public void MalformedWebhookIsRejected(string payload)
    {
        using var http = new HttpClient();
        var provider = new PayOSPaymentProvider(http, Configuration());
        Assert.Throws<TransactionException>(() => provider.VerifyWebhook(JsonSerializer.Deserialize<JsonElement>(payload)));
    }

    [Fact]
    public async Task CreationSendsOfficialRequestSignatureAndMerchantHeaders()
    {
        var handler = new Handler(async message =>
        {
            Assert.Equal("https://api-merchant.payos.vn/v2/payment-requests", message.RequestUri!.AbsoluteUri);
            Assert.Equal("client", message.Headers.GetValues("x-client-id").Single());
            Assert.Equal("api", message.Headers.GetValues("x-api-key").Single());
            var request = JsonSerializer.Deserialize<JsonElement>(await message.Content!.ReadAsStringAsync());
            var canonical = "amount=37000&cancelUrl=https://app.test/cancel&description=UniNet verification&orderCode=123&returnUrl=https://app.test/paid";
            Assert.Equal(Hmac(canonical), request.GetProperty("signature").GetString());
            Assert.Equal(37000, request.GetProperty("amount").GetInt64());
            return JsonResponse("""
                {"code":"00","data":{"orderCode":123,"amount":37000,"currency":"VND",
                 "paymentLinkId":"test","status":"PENDING","checkoutUrl":"https://pay.payos.vn/web/test"},
                 "signature":"invalid"}
                """);
        });
        using var http = new HttpClient(handler);
        var provider = new PayOSPaymentProvider(http, Configuration());
        var error = await Assert.ThrowsAsync<PaymentProviderException>(() => provider.CreatePaymentAsync(
            new("123", 37000, "UniNet verification", "https://app.test/paid", "https://app.test/cancel",
                DateTimeOffset.UtcNow.AddMinutes(30)), default));
        Assert.Equal("INVALID_PROVIDER_SIGNATURE", error.Code);
        Assert.False(error.DefinitivelyRejected);
    }

    [Theory]
    [InlineData("PAID", PaymentStatus.Success)]
    [InlineData("PENDING", PaymentStatus.Pending)]
    [InlineData("PROCESSING", PaymentStatus.Pending)]
    [InlineData("CANCELLED", PaymentStatus.Failed)]
    [InlineData("EXPIRED", PaymentStatus.Failed)]
    [InlineData("UNKNOWN", PaymentStatus.Pending)]
    public async Task ReconciliationMapsProviderStatusesConservatively(string status, PaymentStatus expected)
    {
        using var http = new HttpClient(new Handler(message =>
        {
            Assert.Equal("https://api-merchant.payos.vn/v2/payment-requests/123", message.RequestUri!.AbsoluteUri);
            return Task.FromResult(JsonResponse(JsonSerializer.Serialize(new
            {
                code = "00", data = new { id = "test", orderCode = 123, amount = 37000, amountPaid = 37000, status }
            })));
        }));
        var provider = new PayOSPaymentProvider(http, Configuration());
        var result = await provider.GetPaymentStatusAsync("123", default);
        Assert.Equal(expected, result.Status);
        Assert.Equal("VND", result.Currency);
    }

    [Fact]
    public async Task ValidSignedCreationResponseReturnsCheckout()
    {
        var signature = Hmac("amount=37000&checkoutUrl=https://pay.payos.vn/web/test&currency=VND&orderCode=123&paymentLinkId=test&qrCode=000201-test-payload&status=PENDING");
        using var http = new HttpClient(new Handler(_ => Task.FromResult(JsonResponse(JsonSerializer.Serialize(new
        {
            code = "00", signature,
            data = new { orderCode = 123, amount = 37000, currency = "VND", paymentLinkId = "test",
                status = "PENDING", checkoutUrl = "https://pay.payos.vn/web/test", qrCode = "000201-test-payload" }
        })))));
        var result = await new PayOSPaymentProvider(http, Configuration()).CreatePaymentAsync(
            new("123", 37000, "UniNet verification", "https://app.test/paid", "https://app.test/cancel",
                DateTimeOffset.UtcNow.AddMinutes(30)), default);
        Assert.Equal("test", result.PaymentLinkId);
        Assert.Equal("https://pay.payos.vn/web/test", result.CheckoutUrl);
        Assert.Equal("000201-test-payload", result.QrCode);
        Assert.Equal(PaymentStatus.Pending, result.Status);
    }

    [Theory]
    [InlineData(400, true)]
    [InlineData(401, true)]
    [InlineData(403, true)]
    [InlineData(409, false)]
    [InlineData(429, false)]
    [InlineData(500, false)]
    [InlineData(200, false)]
    public async Task OnlyExplicitPreCreationRejectionsAreSafeToRetry(int httpStatus, bool definite)
    {
        using var http = new HttpClient(new Handler(_ => Task.FromResult(
            JsonResponse("{\"code\":\"ERROR\",\"desc\":\"redacted\",\"data\":null}", (HttpStatusCode)httpStatus))));
        var provider = new PayOSPaymentProvider(http, Configuration());
        var error = await Assert.ThrowsAsync<PaymentProviderException>(() => provider.CreatePaymentAsync(
            new("123", 37000, "UniNet verification", "https://app.test/paid", "https://app.test/cancel",
                DateTimeOffset.UtcNow.AddMinutes(30)), default));
        Assert.Equal(definite, error.DefinitivelyRejected);
        Assert.DoesNotContain("redacted", error.Message);
    }

    [Fact]
    public async Task NetworkTimeoutHasUnknownOutcome()
    {
        using var http = new HttpClient(new Handler(_ => throw new TaskCanceledException()));
        var provider = new PayOSPaymentProvider(http, Configuration());
        var error = await Assert.ThrowsAsync<PaymentProviderException>(() => provider.GetPaymentStatusAsync("123", default));
        Assert.False(error.DefinitivelyRejected);
        Assert.Equal("PROVIDER_STATUS_UNKNOWN", error.Code);
    }

    [Fact]
    public void MissingConfigurationReturnsServiceUnavailable()
    {
        using var http = new HttpClient();
        var provider = new PayOSPaymentProvider(http, new ConfigurationBuilder().Build());
        Assert.Equal(503, Assert.Throws<TransactionException>(provider.EnsureConfigured).Status);
    }

    private static string Hmac(string canonical) => Convert.ToHexString(HMACSHA256.HashData(
        Encoding.UTF8.GetBytes(Key), Encoding.UTF8.GetBytes(canonical))).ToLowerInvariant();
    private static HttpResponseMessage JsonResponse(string json, HttpStatusCode status = HttpStatusCode.OK)
        => new(status) { Content = new StringContent(json, Encoding.UTF8, "application/json") };
    private sealed class Handler(Func<HttpRequestMessage, Task<HttpResponseMessage>> respond) : HttpMessageHandler
    {
        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken ct) => respond(request);
    }
}
